#!/bin/bash
# Create / refresh the isolated VM checkout used by the Pradium optimization
# loop. Read-only w.r.t. the existing campaign checkout at /workspace/pradium.
#
#   usage: setup_vm_checkout.sh [branch] [dest]
set -euo pipefail

BRANCH=${1:?branch name}
DEST=${2:-/workspace/exp/pradium}
REPO=https://github.com/Pranavharshans/Pradium-Engine.git

mkdir -p /workspace/exp

if [ ! -d "$DEST/.git" ]; then
  git clone --branch "$BRANCH" "$REPO" "$DEST"
else
  git -C "$DEST" fetch --all --prune
  git -C "$DEST" checkout "$BRANCH"
  git -C "$DEST" pull --ff-only origin "$BRANCH" || true
fi

# Engine submodule (source only; never modified in place by experiment work)
git -C "$DEST" submodule update --init --recursive

# Frozen materialized prompts (generated by the campaign with the frozen
# tokenizer revision). The harness validates the frozen corpus before any run.
if [ ! -d "$DEST/benchmarks/corpus/materialized" ]; then
  cp -a /workspace/pradium/benchmarks/corpus/materialized "$DEST/benchmarks/corpus/materialized"
fi

git -C "$DEST" log --oneline -1
git -C "$DEST" status --short | head
